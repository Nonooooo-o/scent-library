// Regenerates styles/fonts.css from the installed @fontsource packages.
// Only woff2 sources are kept (the CSP-safe, self-hosted fonts load from /assets).
// Noto Serif SC keeps its unicode-range slices, so a page only downloads the
// glyph chunks it actually uses. Run: node scripts/build-font-css.mjs
import fs from 'node:fs';
import path from 'node:path';

const root = process.cwd();
const pick = [
  ['cormorant-garamond', ['300'], /latin-300/],
  ['noto-serif-sc', ['400'], null],
];
let out = '/* Generated by scripts/build-font-css.mjs — do not edit by hand. */\n';
for (const [pkg, weights, subset] of pick) {
  for (const w of weights) {
    const file = path.join(root, 'node_modules/@fontsource', pkg, `${w}.css`);
    const css = fs.readFileSync(file, 'utf8');
    for (const block of css.match(/@font-face\s*{[^}]+}/g)) {
      const woff2 = block.match(/url\(\.\/files\/([^)]+\.woff2)\)/)[1];
      if (subset && !subset.test(woff2)) continue;
      out += block
        .replace(/src:[^;]+;/, `src: url(../node_modules/@fontsource/${pkg}/files/${woff2}) format('woff2');`)
        + '\n';
    }
  }
}
fs.writeFileSync(path.join(root, 'styles/fonts.css'), out);
console.log('styles/fonts.css written', out.length, 'bytes');
